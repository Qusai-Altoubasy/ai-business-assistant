-- The vector type, distance operators and HNSW index method come from pgvector.
CREATE EXTENSION IF NOT EXISTS vector;

-- One row per knowledge-base chunk. Rows are replaced by re-indexing, not edited by users.
CREATE TABLE knowledge_chunks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source TEXT NOT NULL,
    section TEXT NOT NULL,
    rule_id TEXT,
    chunk_index INTEGER NOT NULL,
    content TEXT NOT NULL,
    content_hash TEXT NOT NULL,
    -- 768 is the output dimensionality requested from the embedding model.
    -- Every stored and query vector must have this size, so changing it needs a new migration and re-embedding.
    embedding VECTOR(768) NOT NULL,
    -- Vectors from different models or model versions are not comparable.
    -- Storing the model per row lets re-indexing find and replace chunks embedded with another model.
    embedding_model TEXT NOT NULL,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT knowledge_chunks_source_chunk_index_unique UNIQUE (source, chunk_index)
);

-- Retrieval ranks chunks by cosine distance (<=>), so the HNSW index uses the cosine operator class.
CREATE INDEX knowledge_chunks_embedding_hnsw_idx
    ON knowledge_chunks USING hnsw (embedding vector_cosine_ops);
